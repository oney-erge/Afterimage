#!/usr/bin/env python3
"""Regenerate results/INDEX.md from the actual contents of results/*.json.

This exists because a hand-written index rots exactly like the doc drift
this project has already been bitten by (see the H1/H4 registry correction
in CHANGELOG.md): a table listing 39 files by hand goes stale the moment a
40th is added. Every field here is either read directly from a result JSON
or computed by grepping the docs for the filename, so there is nothing to
remember to update by hand -- rerun this script instead.

Usage:
    python scripts/build_results_index.py > results/INDEX.md
"""
from __future__ import annotations

import pathlib
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS_DIR = REPO_ROOT / "results"


def cited_from(filename: str) -> str:
    proc = subprocess.run(
        ["grep", "-rl", filename, "docs", "README.md"],
        capture_output=True, text=True, cwd=REPO_ROOT)
    hits = sorted({pathlib.Path(line).stem for line in proc.stdout.splitlines()})
    return ", ".join(hits) if hits else "-"


def row_for(path: pathlib.Path) -> str | None:
    import json
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None
    hyp = data.get("hypothesis_id") or "-"
    status = data.get("status") or "-"
    if status == "running":
        status += " (interrupted)"
    elif "failed" in path.name:
        status += " (failed run)"
    level = (data.get("evidence_level") or "-").replace("_", " ")
    model = (data.get("model") or "-").split("/")[-1]
    return "| `%s` | %s | %s | %s | %s | %s |" % (
        path.name, hyp, status, level, model, cited_from(path.name))


def main() -> int:
    top_level = sorted(p for p in RESULTS_DIR.glob("*.json"))
    campaign_dirs = sorted(p for p in RESULTS_DIR.iterdir()
                           if p.is_dir() and not p.name.startswith("."))

    print("# Results index")
    print()
    print("Generated by `scripts/build_results_index.py` from the actual "
          "contents of `results/*.json` -- do not hand-edit this file, "
          "regenerate it instead:")
    print()
    print("```bash")
    print("python scripts/build_results_index.py > results/INDEX.md")
    print("```")
    print()
    print("\"Cited from\" is every tracked doc whose text contains the exact "
          "filename, found by grep; a `-` means no current doc cites that "
          "file by name, not that it is unused (an aggregate table drawn "
          "from a directory of runs, for instance, cites the directory, "
          "not each JSON individually).")
    print()
    print("| File | Hypothesis | Status | Level | Model | Cited from |")
    print("|---|---|---|---|---|---|")
    for path in top_level:
        line = row_for(path)
        if line:
            print(line)

    if campaign_dirs:
        print()
        print("## Nested campaign directories")
        print()
        print("Each holds one multi-model campaign's per-stage checkpoints; "
              "see [`docs/CROSS_MODEL_BENCHMARK_2026-08-22.md`]"
              "(../docs/CROSS_MODEL_BENCHMARK_2026-08-22.md) for the "
              "controlling interpretation, and `results/README.md` for the "
              "runner and resume commands.")
        print()
        print("| Directory | Files |")
        print("|---|---:|")
        for d in campaign_dirs:
            count = sum(1 for _ in d.rglob("*") if _.is_file())
            print("| `%s/` | %d |" % (d.name, count))

    return 0


if __name__ == "__main__":
    sys.exit(main())
